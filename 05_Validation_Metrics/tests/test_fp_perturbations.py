@pytest.fixture
def local_judge_tokenizer():
    try:
        return lib.load_tokenizer(lib.JUDGE_TOKENIZER_ID)
    except OSError:
        pytest.skip("Optional integration check requires a locally cached Gemma tokenizer")


def test_truncate_like_judge_matches_judge_encode_budget(local_judge_tokenizer):
    tok = local_judge_tokenizer
    text = "Refusal first. " + "Later prevention item. " * 80
    cut, n_ids = lib.truncate_like_judge(text, 64, tokenizer=tok, skip_special_tokens=True)
    raw_ids = tok(text, max_length=64, truncation=True)["input_ids"]
    assert n_ids == len(raw_ids) == 64
    # Stored cut is special-token-free; re-encoding should stay <= 64 + BOS already in budget.
    assert len(tok(cut)["input_ids"]) <= 65
    assert cut
    assert "Refusal first" in cut


def test_judge_decode_includes_bos_special_token(local_judge_tokenizer):
    """Production ``_truncate`` decodes BOS into the template {response} string."""
    tok = local_judge_tokenizer
    with_special, n = lib.truncate_like_judge(
        "hello world", 16, tokenizer=tok, skip_special_tokens=False
    )
    assert n >= 2
    assert with_special.startswith("<bos>") or with_special.startswith("hello")


def test_pad_exceeds_judge_window(local_judge_tokenizer):
    tok = local_judge_tokenizer
    padded = lib.pad_to_min_tokens("Short refusal.", 700, tokenizer=tok)
    assert lib.count_tokens(padded, tokenizer=tok) >= 700
    assert "robustness check" in padded
    assert "Short refusal." in padded


def test_keep_suffix_drops_opening(local_judge_tokenizer):
    tok = local_judge_tokenizer
    text = "OPENING REFUSAL. " + ("list item about awareness. " * 100)
    tail, _n = lib.keep_suffix_tokens(text, 32, tokenizer=tok)
    assert "OPENING REFUSAL" not in tail
    assert "awareness" in tail


